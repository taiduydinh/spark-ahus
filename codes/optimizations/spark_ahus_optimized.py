def parse_external_utilities(path: str) -> Dict[int, float]:
    utilities: Dict[int, float] = {}
    with open(path, "r", encoding="utf-8") as reader:
        for raw in reader:
            line = raw.strip()
            if not line or line[0] in "#%@":
                continue
            key, value = line.split(":", 1)
            item = int(key.strip())
            util = float(value.strip())
            if util < 0:
                raise ValueError(
                    "Spark-AHUS currently supports the standard positive-utility "
                    f"HUSPM setting; negative external utility for item {item}: {util}"
                )
            utilities[item] = util
    return utilities


def _parse_item_token(token: str) -> Tuple[int, float]:
    left = token.find("[")
    right = token.rfind("]")
    if left <= 0 or right <= left:
        raise ValueError(f"Invalid item token: {token!r}")
    return int(token[:left]), float(token[left + 1:right])


def _declared_sequence_utility(tokens: Sequence[str]) -> Optional[float]:
    for token in reversed(tokens):
        if token.startswith("SUtility:"):
            return float(token.split(":", 1)[1])
        if token.startswith("#UTIL:"):
            return float(token.split(":", 1)[1])
    return None


def parse_sequence_line(
    line: str,
    value_mode: str,
    external_utility: Optional[Dict[int, float]],
) -> Tuple[List[List[Tuple[int, float]]], float]:
    """Parse one positive-utility sequential record.

    Returns:
        itemsets: list of itemsets, each containing (original_item, utility)
        sequence_utility: declared SU when present, otherwise calculated SU
    """
    tokens = line.split()
    declared_su = _declared_sequence_utility(tokens)

    itemsets: List[List[Tuple[int, float]]] = []
    current: List[Tuple[int, float]] = []
    calculated_su = 0.0

    for token in tokens:
        if token == "-1":
            if current:
                current.sort(key=lambda x: x[0])
                itemsets.append(current)
                current = []
        elif token == "-2":
            break
        elif token.startswith("SUtility:") or token.startswith("#UTIL:"):
            break
        elif token and not token.startswith("-"):
            item, raw_value = _parse_item_token(token)
            if value_mode == "quantity":
                if external_utility is None:
                    raise ValueError(
                        "--value-mode quantity requires --external-utility"
                    )
                try:
                    eu = external_utility[item]
                except KeyError as exc:
                    raise KeyError(
                        f"External utility for item {item} is missing"
                    ) from exc
                utility = raw_value * eu
            elif value_mode == "utility":
                utility = raw_value
            else:
                raise ValueError(f"Unknown value mode: {value_mode}")

            if utility < 0:
                raise ValueError(
                    "Spark-AHUS currently supports positive utilities only; "
                    f"item {item} has occurrence utility {utility}"
                )
            calculated_su += utility
            current.append((item, float(utility)))

    if current:
        current.sort(key=lambda x: x[0])
        itemsets.append(current)

    sequence_utility = (
        float(declared_su) if declared_su is not None else float(calculated_su)
    )
    if sequence_utility < 0:
        raise ValueError("Negative sequence utility is not supported.")
    return itemsets, sequence_utility


def is_data_line(raw: str) -> bool:
    s = raw.strip()
    return bool(s) and s[0] not in "#%@"


# ---------------------------------------------------------------------------
# Pure-array partition representation
# ---------------------------------------------------------------------------

@dataclass
class PartitionBlock:
    partition_id: int
    total_utility: float          # original utility mass of all valid sequences
    sequence_count: int           # original valid sequences in the partition
    active_sequence_count: int    # sequences with >=1 globally promising item

    # Active sequences are concatenated into flat arrays.
    seq_offsets: np.ndarray       # int64, len = active_sequence_count + 1
    items: np.ndarray             # int32 dense item ids
    utilities: np.ndarray         # float64 occurrence utilities
    remaining: np.ndarray         # float64 utility strictly after each position
    itemsets: np.ndarray          # int32 local itemset id within a sequence
    pos_sid: np.ndarray           # int32 active sequence id for each position

    # CSR-like root occurrence index: occurrences grouped by item.
    root_items: np.ndarray        # sorted unique dense item ids
    root_offsets: np.ndarray      # int64, len = len(root_items) + 1
    root_order: np.ndarray        # int32 positions grouped by item, stable by pos

    def n_occurrences(self) -> int:
        return int(self.items.size)

    def seq_end(self, sid: int) -> int:
        return int(self.seq_offsets[sid + 1])

    def root_positions(self, item: int) -> np.ndarray:
        if self.root_items.size == 0:
            return np.empty(0, dtype=np.int32)
        idx = int(np.searchsorted(self.root_items, item))
        if idx >= self.root_items.size or int(self.root_items[idx]) != item:
            return np.empty(0, dtype=np.int32)
        start = int(self.root_offsets[idx])
        end = int(self.root_offsets[idx + 1])
        return self.root_order[start:end]


def summarize_partition(
    lines: Iterable[str],
    value_mode: str,
    external_utility: Optional[Dict[int, float]],
) -> Iterator[Tuple[float, int, Dict[int, float]]]:
    total_utility = 0.0
    count = 0
    local_swu: Dict[int, float] = {}

    for raw in lines:
        if not is_data_line(raw):
            continue
        itemsets, sequence_utility = parse_sequence_line(
            raw.strip(), value_mode, external_utility
        )
        total_utility += sequence_utility
        count += 1
        seen = set()
        for itemset in itemsets:
            for item, _ in itemset:
                seen.add(item)
        for item in seen:
            local_swu[item] = local_swu.get(item, 0.0) + sequence_utility

    yield (total_utility, count, local_swu)


def pack_partition(
    partition_id: int,
    lines: Iterable[str],
    value_mode: str,
    external_utility: Optional[Dict[int, float]],
    dense_map: Dict[int, int],
) -> Iterator[PartitionBlock]:
    seq_offsets: List[int] = [0]
    items: List[int] = []
    utils: List[float] = []
    itemsets: List[int] = []
    pos_sid: List[int] = []

    total_utility = 0.0
    sequence_count = 0
    active_sid = 0

    for raw in lines:
        if not is_data_line(raw):
            continue
        parsed_itemsets, sequence_utility = parse_sequence_line(
            raw.strip(), value_mode, external_utility
        )
        total_utility += sequence_utility
        sequence_count += 1

        local_itemset_id = 0
        before = len(items)

        for itemset in parsed_itemsets:
            kept: List[Tuple[int, float]] = []
            for original_item, util in itemset:
                dense = dense_map.get(original_item)
                if dense is not None:
                    kept.append((dense, util))

            if not kept:
                continue

            kept.sort(key=lambda x: x[0])
            for dense, util in kept:
                items.append(int(dense))
                utils.append(float(util))
                itemsets.append(local_itemset_id)
                pos_sid.append(active_sid)
            local_itemset_id += 1

        if len(items) > before:
            active_sid += 1
            seq_offsets.append(len(items))

    if total_utility <= 0 and sequence_count == 0:
        return

    items_a = np.asarray(items, dtype=np.int32)
    utils_a = np.asarray(utils, dtype=np.float64)
    itemsets_a = np.asarray(itemsets, dtype=np.int32)
    pos_sid_a = np.asarray(pos_sid, dtype=np.int32)
    seq_offsets_a = np.asarray(seq_offsets, dtype=np.int64)

    remaining_a = np.zeros(items_a.size, dtype=np.float64)
    for sid in range(active_sid):
        start = int(seq_offsets_a[sid])
        end = int(seq_offsets_a[sid + 1])
        rem = 0.0
        for pos in range(end - 1, start - 1, -1):
            remaining_a[pos] = rem
            rem += float(utils_a[pos])

    if items_a.size:
        # Stable sort preserves sequence/position order within each item group.
        root_order = np.argsort(items_a, kind="stable").astype(np.int32, copy=False)
        grouped_items = items_a[root_order]
        root_items, counts = np.unique(grouped_items, return_counts=True)
        root_items = root_items.astype(np.int32, copy=False)
        root_offsets = np.empty(root_items.size + 1, dtype=np.int64)
        root_offsets[0] = 0
        np.cumsum(counts, out=root_offsets[1:])
    else:
        root_order = np.empty(0, dtype=np.int32)
        root_items = np.empty(0, dtype=np.int32)
        root_offsets = np.zeros(1, dtype=np.int64)

    yield PartitionBlock(
        partition_id=int(partition_id),
        total_utility=float(total_utility),
        sequence_count=int(sequence_count),
        active_sequence_count=int(active_sid),
        seq_offsets=seq_offsets_a,
        items=items_a,
        utilities=utils_a,
        remaining=remaining_a,
        itemsets=itemsets_a,
        pos_sid=pos_sid_a,
        root_items=root_items,
        root_offsets=root_offsets,
        root_order=root_order,
    )


# ---------------------------------------------------------------------------
# Optional exact-safe global item-presence SWU pruning
# ---------------------------------------------------------------------------

def global_presence_records(
    lines: Iterable[str],
    value_mode: str,
    external_utility: Optional[Dict[int, float]],
    dense_map: Dict[int, int],
) -> Iterator[Tuple[float, Tuple[int, ...]]]:
    """Sequence utility and DISTINCT promising item IDs, ignoring order.

    A sequential pattern can only occur in sequences containing *all* its
    distinct items. Therefore the sum of full sequence utilities across this
    intersection is a valid upper bound on exact pattern utility. This bound
    is global, unlike the partition-adaptive local threshold.
    """
    for raw in lines:
        if not is_data_line(raw):
            continue
        itemsets, su = parse_sequence_line(raw, value_mode, external_utility)
        actual_su = math.fsum(util for group in itemsets for _, util in group)
        if actual_su > su + max(1e-7, abs(actual_su) * 1e-9):
            raise ValueError(
                "Global presence pruning needs a sequence-utility bound "
                f"at least as large as its item utilities: declared={su}, "
                f"calculated={actual_su}. Correct SUtility or disable pruning."
            )
        present = set()
        for itemset in itemsets:
            for original_item, _ in itemset:
                item = dense_map.get(original_item)
                if item is not None:
                    present.add(int(item))
        yield float(su), tuple(sorted(present))


def build_global_presence_index(
    records: Iterable[Tuple[float, Sequence[int]]],
    promising_item_count: int,
) -> Tuple[Dict[int, int], Tuple[float, ...]]:
    """Create compressed Python-int sequence bitmaps for globally promising items."""
    masks: Dict[int, int] = {i: 0 for i in range(promising_item_count)}
    utilities: List[float] = []
    for sid, (su, items) in enumerate(records):
        utilities.append(float(su))
        bit = 1 << sid
        for item in items:
            masks[int(item)] |= bit
    return masks, tuple(utilities)


class GlobalPresenceSWUBound:
    """Conservative global item-presence bound; cached by sequence bitmap.

    A prefix cannot recover after its supporting-sequence upper bound falls
    below the global utility threshold. Duplicated items keep the same bitmap.
    """

    def __init__(
        self,
        masks: Dict[int, int],
        utilities: Sequence[float],
        threshold: float,
    ):
        self.masks = masks
        self.utilities = utilities
        self.threshold = float(threshold)
        # Guard against floating addition ordering and near-threshold rounds.
        self.epsilon = max(1e-7, abs(self.threshold) * 1e-9)

        @lru_cache(maxsize=8192)
        def can_reach(mask: int) -> bool:
            remaining = int(mask)
            total = 0.0
            while remaining:
                low = remaining & -remaining
                total += self.utilities[low.bit_length() - 1]
                if total + self.epsilon >= self.threshold:
                    return True
                remaining ^= low
            return total + self.epsilon >= self.threshold

        self.can_reach = can_reach

    def root_mask(self, item: int) -> int:
        return self.masks.get(int(item), 0)

    def child_mask(self, parent_mask: int, item: int) -> int:
        return parent_mask & self.masks.get(int(item), 0)


# ---------------------------------------------------------------------------
# Local pure-array AHUS miner
# ---------------------------------------------------------------------------

@dataclass
class Projection:
    positions: np.ndarray  # int32, sorted by global position
    prefix_utilities: np.ndarray  # float64, same length


@dataclass
class LocalMiningStats:
    partition_id: int
    local_min_utility: float
    local_patterns: int
    expanded_prefixes: int
    generated_extensions: int
    materialized_extensions: int
    occurrences: int
    active_sequences: int
    global_swu_pruned_extensions: int


class PureArrayLocalAHUS:
    """AHUS-style DFS over one partition using compact flat arrays.

    The key memory optimization is bound-first materialization: candidate
    extension upper bounds are accumulated first.  A child projection is only
    materialized if its bound can still reach the local threshold.
    """

    def __init__(
        self,
        block: PartitionBlock,
        min_utility: float,
        max_pattern_length: int,
        global_bound: Optional[GlobalPresenceSWUBound] = None,
    ):
        self.block = block
        self.global_bound = global_bound
        self.min_utility = float(min_utility)
        self.max_pattern_length = int(max_pattern_length)

        self.local_patterns = 0
        self.expanded_prefixes = 0
        self.generated_extensions = 0
        self.materialized_extensions = 0
        self.global_swu_pruned_extensions = 0

    def _root_projection(self, item: int) -> Projection:
        pos = self.block.root_positions(item)
        if pos.size == 0:
            return Projection(
                np.empty(0, dtype=np.int32),
                np.empty(0, dtype=np.float64),
            )
        return Projection(
            positions=pos.astype(np.int32, copy=False),
            prefix_utilities=self.block.utilities[pos].astype(
                np.float64, copy=False
            ),
        )

    def _exact_utility(self, projection: Projection) -> float:
        pos = projection.positions
        pus = projection.prefix_utilities
        if pos.size == 0:
            return 0.0

        total = 0.0
        last_sid = -1
        best = NEG_INF
        for k in range(pos.size):
            sid = int(self.block.pos_sid[int(pos[k])])
            pu = float(pus[k])
            if sid != last_sid:
                if last_sid >= 0:
                    total += best
                last_sid = sid
                best = pu
            elif pu > best:
                best = pu
        if last_sid >= 0:
            total += best
        return total

    def _future_peu(self, projection: Projection) -> float:
        """Upper bound used only to decide whether descendants may exist."""
        pos = projection.positions
        pus = projection.prefix_utilities
        if pos.size == 0:
            return 0.0

        total = 0.0
        last_sid = -1
        best = 0.0
        for k in range(pos.size):
            p = int(pos[k])
            sid = int(self.block.pos_sid[p])
            rem = float(self.block.remaining[p])
            # If no utility remains, this embedding has no possible extension.
            value = float(pus[k]) + rem if rem > 0 else 0.0
            if sid != last_sid:
                if last_sid >= 0:
                    total += best
                last_sid = sid
                best = value
            elif value > best:
                best = value
        if last_sid >= 0:
            total += best
        return total

    @staticmethod
    def _last_item(pattern: Pattern) -> int:
        for token in reversed(pattern):
            if token != -1:
                return int(token)
        raise ValueError("Pattern contains no item.")

    def _discover_extension_bounds(
        self,
        projection: Projection,
        last_item: int,
    ) -> Tuple[Dict[int, float], Dict[int, float]]:
        """Compute exact-safe child upper bounds without building child DBs.

        For each sequence and child item, keep the maximum value of
            prefix_utility + child_utility + remaining_utility(child)
        over reachable embeddings, then sum these maxima across sequences.

        S-extension bounds are computed by a sequence sweep: for every later
        itemset we keep the best prefix utility from strictly earlier itemsets.
        This avoids rescanning the whole suffix once per projected embedding.

        Two maps are returned for I- and S-extensions.
        """
        b = self.block
        i_bounds: Dict[int, float] = {}
        s_bounds: Dict[int, float] = {}

        pos = projection.positions
        pus = projection.prefix_utilities
        n = int(pos.size)
        k = 0

        while k < n:
            sid = int(b.pos_sid[int(pos[k])])
            seq_start = int(b.seq_offsets[sid])
            seq_end = b.seq_end(sid)

            local_i: Dict[int, float] = {}
            local_s: Dict[int, float] = {}
            parent_best_by_itemset: Dict[int, float] = {}

            # Consume all projected endings for this sequence.
            while k < n and int(b.pos_sid[int(pos[k])]) == sid:
                p = int(pos[k])
                base = float(pus[k])
                iset = int(b.itemsets[p])

                old_base = parent_best_by_itemset.get(iset)
                if old_base is None or base > old_base:
                    parent_best_by_itemset[iset] = base

                # I-extension: same itemset, canonical ascending item order.
                q = p + 1
                while q < seq_end and int(b.itemsets[q]) == iset:
                    item = int(b.items[q])
                    if item > last_item:
                        ub = (
                            base
                            + float(b.utilities[q])
                            + float(b.remaining[q])
                        )
                        old = local_i.get(item)
                        if old is None or ub > old:
                            local_i[item] = ub
                    q += 1

                k += 1

            # S-extension: sweep itemsets once.  A target in itemset J may
            # extend only embeddings ending in itemsets strictly before J.
            best_prior_base = NEG_INF
            q = seq_start
            while q < seq_end:
                current_iset = int(b.itemsets[q])
                itemset_start = q
                while q < seq_end and int(b.itemsets[q]) == current_iset:
                    q += 1
                itemset_end = q

                if best_prior_base != NEG_INF:
                    for r in range(itemset_start, itemset_end):
                        item = int(b.items[r])
                        ub = (
                            best_prior_base
                            + float(b.utilities[r])
                            + float(b.remaining[r])
                        )
                        old = local_s.get(item)
                        if old is None or ub > old:
                            local_s[item] = ub

                parent_base = parent_best_by_itemset.get(current_iset)
                if parent_base is not None and parent_base > best_prior_base:
                    best_prior_base = parent_base

            for item, value in local_i.items():
                i_bounds[item] = i_bounds.get(item, 0.0) + value
            for item, value in local_s.items():
                s_bounds[item] = s_bounds.get(item, 0.0) + value

        return i_bounds, s_bounds

    def _materialize_child(
        self,
        projection: Projection,
        target_item: int,
        extension_type: str,
    ) -> Projection:
        """Build only one surviving child projection at a time.

        I-extension materialization keeps the maximum utility for a target
        ending position.  S-extension uses an itemset sweep so that each target
        occurrence is visited once per sequence.
        """
        b = self.block
        pos = projection.positions
        pus = projection.prefix_utilities

        if extension_type == "I":
            best_at_pos: Dict[int, float] = {}
            for k in range(pos.size):
                p = int(pos[k])
                base = float(pus[k])
                sid = int(b.pos_sid[p])
                iset = int(b.itemsets[p])
                seq_end = b.seq_end(sid)

                q = p + 1
                while q < seq_end and int(b.itemsets[q]) == iset:
                    if int(b.items[q]) == target_item:
                        new_pu = base + float(b.utilities[q])
                        old = best_at_pos.get(q)
                        if old is None or new_pu > old:
                            best_at_pos[q] = new_pu
                    q += 1

            if not best_at_pos:
                return Projection(
                    np.empty(0, dtype=np.int32),
                    np.empty(0, dtype=np.float64),
                )

            positions = np.fromiter(
                sorted(best_at_pos.keys()),
                dtype=np.int32,
                count=len(best_at_pos),
            )
            prefix_utilities = np.fromiter(
                (best_at_pos[int(p)] for p in positions),
                dtype=np.float64,
                count=len(best_at_pos),
            )
            return Projection(positions, prefix_utilities)

        if extension_type == "S":
            out_pos: List[int] = []
            out_pu: List[float] = []

            n = int(pos.size)
            k = 0
            while k < n:
                sid = int(b.pos_sid[int(pos[k])])
                seq_start = int(b.seq_offsets[sid])
                seq_end = b.seq_end(sid)
                parent_best_by_itemset: Dict[int, float] = {}

                while k < n and int(b.pos_sid[int(pos[k])]) == sid:
                    p = int(pos[k])
                    iset = int(b.itemsets[p])
                    base = float(pus[k])
                    old = parent_best_by_itemset.get(iset)
                    if old is None or base > old:
                        parent_best_by_itemset[iset] = base
                    k += 1

                best_prior_base = NEG_INF
                q = seq_start
                while q < seq_end:
                    current_iset = int(b.itemsets[q])
                    itemset_start = q
                    while q < seq_end and int(b.itemsets[q]) == current_iset:
                        q += 1
                    itemset_end = q

                    if best_prior_base != NEG_INF:
                        for r in range(itemset_start, itemset_end):
                            if int(b.items[r]) == target_item:
                                out_pos.append(r)
                                out_pu.append(
                                    best_prior_base + float(b.utilities[r])
                                )

                    parent_base = parent_best_by_itemset.get(current_iset)
                    if (
                        parent_base is not None
                        and parent_base > best_prior_base
                    ):
                        best_prior_base = parent_base

            if not out_pos:
                return Projection(
                    np.empty(0, dtype=np.int32),
                    np.empty(0, dtype=np.float64),
                )
            return Projection(
                np.asarray(out_pos, dtype=np.int32),
                np.asarray(out_pu, dtype=np.float64),
            )

        raise ValueError(f"Unknown extension type: {extension_type}")

    def iter_patterns(self) -> Iterator[Tuple[Pattern, float]]:
        b = self.block
        if b.active_sequence_count == 0 or b.items.size == 0:
            return

        # Stack entries: pattern, projection, item count, global item mask.
        # The presence mask only matters with optional global SWU pruning.
        stack: List[Tuple[Pattern, Projection, int, int]] = []

        for item_np in b.root_items[::-1]:
            item = int(item_np)
            global_mask = self.global_bound.root_mask(item) if self.global_bound else 0
            projection = self._root_projection(item)
            exact = self._exact_utility(projection)
            pattern = (item,)
            if exact >= self.min_utility:
                self.local_patterns += 1
                yield pattern, exact
            if (
                self.max_pattern_length > 1
                and self._future_peu(projection) >= self.min_utility
            ):
                stack.append((pattern, projection, 1, global_mask))

        while stack:
            pattern, projection, item_count, global_mask = stack.pop()
            self.expanded_prefixes += 1
            last_item = self._last_item(pattern)
            i_bounds, s_bounds = self._discover_extension_bounds(
                projection, last_item
            )

            # Push in reverse lexical order so DFS visits smaller children first.
            children: List[Tuple[str, int, float]] = []
            for item, bound in i_bounds.items():
                self.generated_extensions += 1
                if bound >= self.min_utility:
                    children.append(("I", int(item), float(bound)))
            for item, bound in s_bounds.items():
                self.generated_extensions += 1
                if bound >= self.min_utility:
                    children.append(("S", int(item), float(bound)))

            children.sort(
                key=lambda x: (0 if x[0] == "I" else 1, x[1]),
                reverse=True,
            )

            for ext_type, item, _bound in children:
                child_mask = (
                    self.global_bound.child_mask(global_mask, item)
                    if self.global_bound else 0
                )
                if self.global_bound and not self.global_bound.can_reach(child_mask):
                    self.global_swu_pruned_extensions += 1
                    continue
                child = self._materialize_child(projection, item, ext_type)
                if child.positions.size == 0:
                    continue
                self.materialized_extensions += 1
                exact = self._exact_utility(child)
                new_pattern = (
                    pattern + (item,)
                    if ext_type == "I"
                    else pattern + (-1, item)
                )

                if exact >= self.min_utility:
                    self.local_patterns += 1
                    yield new_pattern, exact

                if (
                    item_count + 1 < self.max_pattern_length
                    and self._future_peu(child) >= self.min_utility
                ):
                    stack.append((new_pattern, child, item_count + 1, child_mask))

    def stats(self) -> LocalMiningStats:
        return LocalMiningStats(
            partition_id=self.block.partition_id,
            local_min_utility=self.min_utility,
            local_patterns=self.local_patterns,
            expanded_prefixes=self.expanded_prefixes,
            generated_extensions=self.generated_extensions,
            materialized_extensions=self.materialized_extensions,
            occurrences=self.block.n_occurrences(),
            active_sequences=self.block.active_sequence_count,
            global_swu_pruned_extensions=self.global_swu_pruned_extensions,
        )


