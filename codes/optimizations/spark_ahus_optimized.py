def decode_pattern(pattern: Pattern, dense_to_original: Sequence[int]) -> Pattern:
    return tuple(
        -1 if token == -1 else int(dense_to_original[int(token)])
        for token in pattern
    )


def format_number(value: float) -> str:
    if abs(value - round(value)) < 1e-9:
        return str(int(round(value)))
    return f"{value:.10f}".rstrip("0").rstrip(".")


def pattern_to_string(pattern: Pattern, utility: float) -> str:
    itemsets: List[List[int]] = [[]]
    for token in pattern:
        if token == -1:
            itemsets.append([])
        else:
            itemsets[-1].append(int(token))
    inside = "".join(
        "(" + " ".join(str(x) for x in itemset) + ")"
        for itemset in itemsets
        if itemset
    )
    return f"<{inside}>:{format_number(utility)}"


class ProcessTreeMemorySampler:
    """Best-effort driver process-tree RSS sampler.

    For publication-quality Spark executor memory, also collect Spark executor
    metrics and/or wrap spark-submit with /usr/bin/time -v.  This sampler is
    intentionally labeled as process-tree telemetry rather than cluster memory.
    """

    def __init__(self, interval: float = 0.1):
        self.interval = float(interval)
        self.peak_bytes = 0
        self._stop = threading.Event()
        self._thread: Optional[threading.Thread] = None

    def _sample_once(self) -> int:
        if psutil is None:
            return 0
        try:
            root = psutil.Process(os.getpid())
            procs = [root] + root.children(recursive=True)
            total = 0
            for p in procs:
                try:
                    total += int(p.memory_info().rss)
                except (psutil.NoSuchProcess, psutil.AccessDenied):
                    pass
            return total
        except Exception:
            return 0

    def _loop(self) -> None:
        while not self._stop.is_set():
            value = self._sample_once()
            if value > self.peak_bytes:
                self.peak_bytes = value
            self._stop.wait(self.interval)

    def start(self) -> None:
        if psutil is None:
            return
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        if self._thread is None:
            return
        self._stop.set()
        self._thread.join(timeout=max(1.0, self.interval * 4))
        value = self._sample_once()
        if value > self.peak_bytes:
            self.peak_bytes = value

    @property
    def peak_mb(self) -> float:
        return self.peak_bytes / (1024.0 * 1024.0)


