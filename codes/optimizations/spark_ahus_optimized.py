@dataclass
class TrieNode:
    terminal_id: int
    i_children: Dict[int, int]
    s_children: Dict[int, int]


@dataclass
class CandidateTrie:
    nodes: List[TrieNode]

    def to_wire(self) -> List[Tuple[int, Dict[int, int], Dict[int, int]]]:
        """Convert to built-in types safe for PySpark broadcast/pickle.

        A class defined by a ``spark-submit`` entrypoint is named ``__main__``
        on the driver, but PySpark workers run under ``pyspark.daemon``.
        Broadcasting a CandidateTrie instance consequently fails when the
        worker unpickles it. Plain tuples, ints and dicts have no such issue.
        """
        return [
            (node.terminal_id, node.i_children, node.s_children)
            for node in self.nodes
        ]

    @staticmethod
    def build(patterns: Sequence[Pattern]) -> "CandidateTrie":
        nodes: List[TrieNode] = [TrieNode(-1, {}, {})]

        for candidate_id, pattern in enumerate(patterns):
            node_id = 0
            mode = "I"
            expecting_item = True

            for token in pattern:
                if token == -1:
                    mode = "S"
                    expecting_item = True
                    continue

                item = int(token)
                node = nodes[node_id]
                children = (
                    node.i_children if mode == "I" else node.s_children
                )
                child_id = children.get(item)
                if child_id is None:
                    child_id = len(nodes)
                    children[item] = child_id
                    nodes.append(TrieNode(-1, {}, {}))
                node_id = child_id
                mode = "I"
                expecting_item = False

            if expecting_item:
                raise ValueError(f"Malformed pattern: {pattern}")
            nodes[node_id].terminal_id = candidate_id

        return CandidateTrie(nodes)


class TrieVerifier:
    def __init__(
        self,
        block: PartitionBlock,
        trie: CandidateTrie | List[Tuple[int, Dict[int, int], Dict[int, int]]],
    ):
        self.block = block
        # Accept both the original in-process trie (core tests) and the
        # pickle-safe wire format broadcast by Spark (real distributed runs).
        self.nodes = trie.to_wire() if isinstance(trie, CandidateTrie) else trie

    def _root_projection(self, item: int) -> Projection:
        pos = self.block.root_positions(item)
        if pos.size == 0:
            return Projection(
                np.empty(0, dtype=np.int32),
                np.empty(0, dtype=np.float64),
            )
        return Projection(
            pos.astype(np.int32, copy=False),
            self.block.utilities[pos].astype(np.float64, copy=False),
        )

    def _exact(self, projection: Projection) -> float:
        if projection.positions.size == 0:
            return 0.0
        total = 0.0
        last_sid = -1
        best = NEG_INF
        for k in range(projection.positions.size):
            p = int(projection.positions[k])
            sid = int(self.block.pos_sid[p])
            pu = float(projection.prefix_utilities[k])
            if sid != last_sid:
                if last_sid >= 0:
                    total += best
                last_sid = sid
                best = pu
            elif pu > best:
                best = pu
        if last_sid >= 0:
            total += best
        return total

    def _child(
        self,
        projection: Projection,
        target_item: int,
        extension_type: str,
    ) -> Projection:
        # Verification uses the same exact projection semantics as local mining.
        miner = PureArrayLocalAHUS(
            self.block, min_utility=0.0, max_pattern_length=2**31 - 1
        )
        return miner._materialize_child(
            projection, target_item, extension_type
        )

    def iter_local_utilities(self) -> Iterator[Tuple[int, float]]:
        stack: List[Tuple[int, Projection]] = []

        # Root patterns are represented as I-children of the trie root.
        for item, node_id in self.nodes[0][1].items():
            projection = self._root_projection(item)
            if projection.positions.size:
                stack.append((node_id, projection))

        while stack:
            node_id, projection = stack.pop()
            terminal_id, i_children, s_children = self.nodes[node_id]

            if terminal_id >= 0:
                utility = self._exact(projection)
                if utility > 0:
                    yield terminal_id, utility

            for item, child_id in i_children.items():
                child = self._child(projection, item, "I")
                if child.positions.size:
                    stack.append((child_id, child))

            for item, child_id in s_children.items():
                child = self._child(projection, item, "S")
                if child.positions.size:
                    stack.append((child_id, child))


