def run_spark(args: argparse.Namespace) -> Dict[str, object]:
    # Import lazily so core correctness tests can run without PySpark installed.
    from pyspark import SparkConf, SparkContext, StorageLevel

    os.environ.setdefault("OMP_NUM_THREADS", "1")
    os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
    os.environ.setdefault("MKL_NUM_THREADS", "1")
    os.environ.setdefault("NUMEXPR_NUM_THREADS", "1")

    conf = SparkConf().setAppName(args.app_name)
    conf.set("spark.python.worker.reuse", "true")
    conf.set("spark.speculation", "false")
    conf.set("spark.serializer", "org.apache.spark.serializer.KryoSerializer")
    conf.set("spark.executorEnv.OMP_NUM_THREADS", "1")
    conf.set("spark.executorEnv.OPENBLAS_NUM_THREADS", "1")
    conf.set("spark.executorEnv.MKL_NUM_THREADS", "1")
    if args.master:
        conf.setMaster(args.master)

    sc = SparkContext.getOrCreate(conf=conf)
    sc.setLogLevel(args.spark_log_level)

    default_parallelism = max(1, sc.defaultParallelism)
    num_partitions = (
        int(args.partitions)
        if args.partitions is not None
        else max(1, default_parallelism * int(args.partition_multiplier))
    )
    shuffle_partitions = (
        int(args.shuffle_partitions)
        if args.shuffle_partitions is not None
        else num_partitions
    )

    external = (
        parse_external_utilities(args.external_utility)
        if args.external_utility
        else None
    )
    external_bc = sc.broadcast(external)

    sampler = ProcessTreeMemorySampler(args.memory_sample_interval)
    sampler.start()
    wall_start = time.perf_counter()

    try:
        # --------------------- pass 1: global SWU ---------------------
        t0 = time.perf_counter()
        lines1 = sc.textFile(args.input, minPartitions=num_partitions)
        summaries = lines1.mapPartitions(
            lambda it: summarize_partition(
                it, args.value_mode, external_bc.value
            )
        ).collect()

        total_utility = sum(x[0] for x in summaries)
        sequence_count = sum(x[1] for x in summaries)
        global_swu: Dict[int, float] = {}
        for _, _, local_map in summaries:
            for item, swu in local_map.items():
                global_swu[item] = global_swu.get(item, 0.0) + float(swu)

        if sequence_count == 0:
            raise ValueError("No valid sequences were found.")
        if total_utility <= 0:
            raise ValueError("Total database utility must be positive.")

        if args.min_utility is not None:
            global_min_utility = float(args.min_utility)
            threshold_ratio = global_min_utility / total_utility
        else:
            threshold_ratio = float(args.min_utility_ratio)
            global_min_utility = threshold_ratio * total_utility

        promising_original = sorted(
            item for item, swu in global_swu.items()
            if swu >= global_min_utility
        )
        dense_map = {
            original: dense
            for dense, original in enumerate(promising_original)
        }
        preprocess1_sec = time.perf_counter() - t0

        if not promising_original:
            # A valid zero-HUSP run still produces an empty patterns file.
            # Required for reproducible exact-output validation.
            if args.output and not args.count_only:
                p = Path(args.output)
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text("", encoding="utf-8")
            sampler.stop()
            result = {
                "algorithm": "Spark-AHUS",
                "sequence_count": sequence_count,
                "total_utility": total_utility,
                "min_utility": global_min_utility,
                "threshold_ratio": threshold_ratio,
                "promising_items": 0,
                "max_pattern_length": int(args.max_pattern_length),
                "local_candidate_count": 0,
                "husp_count": 0,
                "runtime_sec": time.perf_counter() - wall_start,
            }
            if args.stats_json:
                stats_path = Path(args.stats_json)
                stats_path.parent.mkdir(parents=True, exist_ok=True)
                stats_path.write_text(
                    json.dumps(result, indent=2), encoding="utf-8"
                )
            return result

        dense_map_bc = sc.broadcast(dense_map)
        dense_to_original = promising_original

        # ---------------- pass 2: pure-array packing -----------------
        t1 = time.perf_counter()
        lines2 = sc.textFile(args.input, minPartitions=num_partitions)
        blocks = lines2.mapPartitionsWithIndex(
            lambda pid, it: pack_partition(
                pid,
                it,
                args.value_mode,
                external_bc.value,
                dense_map_bc.value,
            )
        ).persist(StorageLevel.MEMORY_AND_DISK)

        block_count = blocks.count()  # materialize
        block_stats = blocks.map(
            lambda b: (
                b.partition_id,
                b.total_utility,
                b.sequence_count,
                b.active_sequence_count,
                b.n_occurrences(),
            )
        ).collect()
        pack_sec = time.perf_counter() - t1

        # -- optional global item-presence bound (correctness-preserving) --
        global_bound_bc = None
        global_bound_preprocess_sec = 0.0
        if args.global_itemset_swu_pruning:
            if (
                sequence_count > args.global_bound_max_sequences
                or len(promising_original) > args.global_bound_max_items
            ):
                raise ValueError(
                    "Global itemset-SWU pruning requested but the database "
                    "exceeds its configured collection guards: "
                    f"sequences={sequence_count:,}, "
                    f"promising_items={len(promising_original):,}. "
                    "Raise --global-bound-max-sequences / "
                    "--global-bound-max-items intentionally, or omit "
                    "--global-itemset-swu-pruning for this case."
                )
            t_bound = time.perf_counter()
            rows = sc.textFile(
                args.input, minPartitions=num_partitions
            ).mapPartitions(
                lambda lines: global_presence_records(
                    lines, args.value_mode, external_bc.value, dense_map_bc.value
                )
            ).collect()
            if len(rows) != sequence_count:
                raise RuntimeError("Global SWU index sequence count mismatch")
            masks, sus = build_global_presence_index(
                rows, len(promising_original)
            )
            del rows
            global_bound_bc = sc.broadcast((masks, sus, global_min_utility))
            global_bound_preprocess_sec = time.perf_counter() - t_bound

        # -------------- partition-adaptive local mining --------------
        t2 = time.perf_counter()

        def mine_block_records(
            block: PartitionBlock,
        ) -> Iterator[Tuple[str, object]]:
            local_min = threshold_ratio * block.total_utility
            global_bound = (
                GlobalPresenceSWUBound(*global_bound_bc.value)
                if global_bound_bc is not None else None
            )
            miner = PureArrayLocalAHUS(
                block=block,
                min_utility=local_min,
                max_pattern_length=args.max_pattern_length,
                global_bound=global_bound,
            )
            for pattern, _local_utility in miner.iter_patterns():
                yield ("P", pattern)
            yield ("S", miner.stats())

        local_records = blocks.flatMap(
            mine_block_records
        ).persist(StorageLevel.MEMORY_AND_DISK)

        local_stats = local_records.filter(
            lambda x: x[0] == "S"
        ).map(lambda x: x[1]).collect()

        candidate_rdd = (
            local_records.filter(lambda x: x[0] == "P")
            .map(lambda x: (x[1], 1))
            .reduceByKey(lambda _a, _b: 1, numPartitions=shuffle_partitions)
            .keys()
            .persist(StorageLevel.MEMORY_AND_DISK)
        )
        candidate_count = candidate_rdd.count()

        if candidate_count > args.max_driver_candidates:
            raise RuntimeError(
                f"Distinct candidate count {candidate_count:,} exceeds "
                f"--max-driver-candidates={args.max_driver_candidates:,}. "
                "Increase the limit if the driver has enough memory, or use a "
                "higher min-utility for the first scaling tests."
            )

        candidates: List[Pattern] = candidate_rdd.collect()
        local_mining_sec = time.perf_counter() - t2

        # ---------------- distributed exact verification -------------
        t3 = time.perf_counter()
        husp_count = 0
        verified_candidates = 0

        writer = None
        if args.output and not args.count_only:
            output_path = Path(args.output)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            writer = output_path.open("w", encoding="utf-8", newline="")

        try:
            chunk_size = max(1, int(args.verification_chunk_size))
            for start in range(0, len(candidates), chunk_size):
                chunk = candidates[start:start + chunk_size]
                # Only broadcast built-in types: never broadcast a class
                # defined in this spark-submit script's __main__ module.
                trie_wire = CandidateTrie.build(chunk).to_wire()
                trie_bc = sc.broadcast(trie_wire)

                local_utils = blocks.flatMap(
                    lambda block: TrieVerifier(
                        block, trie_bc.value
                    ).iter_local_utilities()
                )
                global_utils = dict(
                    local_utils.reduceByKey(
                        lambda a, b: float(a) + float(b),
                        numPartitions=shuffle_partitions,
                    ).collect()
                )

                verified_candidates += len(chunk)
                for cid, pattern in enumerate(chunk):
                    utility = float(global_utils.get(cid, 0.0))
                    if utility + 1e-12 >= global_min_utility:
                        husp_count += 1
                        if writer is not None:
                            decoded = decode_pattern(
                                pattern, dense_to_original
                            )
                            writer.write(
                                pattern_to_string(decoded, utility) + "\n"
                            )

                trie_bc.unpersist(blocking=False)
        finally:
            if writer is not None:
                writer.close()

        verify_sec = time.perf_counter() - t3

        runtime_sec = time.perf_counter() - wall_start
        sampler.stop()

        result: Dict[str, object] = {
            "algorithm": "Spark-AHUS",
            "input": str(args.input),
            "value_mode": args.value_mode,
            "sequence_count": int(sequence_count),
            "total_utility": float(total_utility),
            "min_utility": float(global_min_utility),
            "threshold_ratio": float(threshold_ratio),
            "promising_items": int(len(promising_original)),
            "spark_default_parallelism": int(default_parallelism),
            "database_partitions": int(num_partitions),
            "materialized_blocks": int(block_count),
            "local_candidate_count": int(candidate_count),
            "global_itemset_swu_pruning": bool(global_bound_bc is not None),
            "global_bound_preprocess_sec": float(global_bound_preprocess_sec),
            "global_swu_pruned_extensions": int(sum(
                s.global_swu_pruned_extensions for s in local_stats
            )),
            "verified_candidate_count": int(verified_candidates),
            "husp_count": int(husp_count),
            "max_pattern_length": int(args.max_pattern_length),
            "preprocess_swu_sec": float(preprocess1_sec),
            "pack_arrays_sec": float(pack_sec),
            "local_mining_sec": float(local_mining_sec),
            "global_verification_sec": float(verify_sec),
            "runtime_sec": float(runtime_sec),
            "driver_process_tree_peak_mb": float(sampler.peak_mb),
            "partition_stats": [
                {
                    "partition_id": int(x[0]),
                    "total_utility": float(x[1]),
                    "sequence_count": int(x[2]),
                    "active_sequence_count": int(x[3]),
                    "occurrences": int(x[4]),
                }
                for x in block_stats
            ],
            "local_mining_stats": [
                {
                    "partition_id": int(s.partition_id),
                    "local_min_utility": float(s.local_min_utility),
                    "local_patterns": int(s.local_patterns),
                    "expanded_prefixes": int(s.expanded_prefixes),
                    "generated_extensions": int(s.generated_extensions),
                    "materialized_extensions": int(s.materialized_extensions),
                    "global_swu_pruned_extensions": int(s.global_swu_pruned_extensions),
                    "occurrences": int(s.occurrences),
                    "active_sequences": int(s.active_sequences),
                }
                for s in local_stats
            ],
        }

        if args.stats_json:
            stats_path = Path(args.stats_json)
            stats_path.parent.mkdir(parents=True, exist_ok=True)
            stats_path.write_text(
                json.dumps(result, indent=2), encoding="utf-8"
            )

        candidate_rdd.unpersist()
        local_records.unpersist()
        blocks.unpersist()
        if global_bound_bc is not None:
            global_bound_bc.unpersist(blocking=False)

        return result

    finally:
        sampler.stop()
        try:
            external_bc.unpersist(blocking=False)
        except Exception:
            pass
        if not args.keep_spark_context:
            sc.stop()


