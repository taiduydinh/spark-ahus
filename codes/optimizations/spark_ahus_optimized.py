def validate_args(args: argparse.Namespace) -> None:
    if args.value_mode == "quantity" and not args.external_utility:
        raise ValueError(
            "--value-mode quantity requires --external-utility."
        )
    if args.min_utility is not None and args.min_utility < 0:
        raise ValueError("--min-utility must be nonnegative.")
    if args.min_utility_ratio is not None:
        if not (0.0 <= args.min_utility_ratio <= 1.0):
            raise ValueError("--min-utility-ratio must be in [0,1].")
    if args.max_pattern_length < 1:
        raise ValueError("--max-pattern-length must be >= 1.")
    if args.partitions is not None and args.partitions < 1:
        raise ValueError("--partitions must be >= 1.")
    if args.partition_multiplier < 1:
        raise ValueError("--partition-multiplier must be >= 1.")
    if args.verification_chunk_size < 1:
        raise ValueError("--verification-chunk-size must be >= 1.")
    if args.global_bound_max_sequences < 1 or args.global_bound_max_items < 1:
        raise ValueError("Global SWU presence index guards must be >= 1")
    if args.max_driver_candidates < 1:
        raise ValueError("--max-driver-candidates must be >= 1.")


def main() -> int:
    parser = build_arg_parser()
    args = parser.parse_args()
    try:
        validate_args(args)
        result = run_spark(args)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    print("============= Spark-AHUS =============")
    print(f"Sequences            : {result.get('sequence_count', 0)}")
    print(f"Total utility        : {format_number(float(result.get('total_utility', 0.0)))}")
    print(f"Min utility          : {format_number(float(result.get('min_utility', 0.0)))}")
    print(f"Promising items      : {result.get('promising_items', 0)}")
    print(f"Local candidates     : {result.get('local_candidate_count', 0)}")
    print(f"Exact HUSPs          : {result.get('husp_count', 0)}")
    print(f"Runtime (s)          : {float(result.get('runtime_sec', 0.0)):.6f}")
    print(
        "Driver tree peak MB  : "
        f"{float(result.get('driver_process_tree_peak_mb', 0.0)):.3f}"
    )
    print("======================================")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
