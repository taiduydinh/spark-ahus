#!/usr/bin/env python3
"""
Spark-AHUS: An Adaptive Pure-Array Parallel Framework for
High-Utility Sequential Pattern Mining.

Research prototype for positive-utility HUSPM.

Design:
  1) Distributed global SWU preprocessing.
  2) Partition-local compact pure-array sequence storage.
  3) Partition-adaptive local thresholds:
         delta_j = (delta / TU(D)) * TU(D_j)
     which guarantees that every global HUSP is generated by at least
     one local partition.
  4) Bound-first local AHUS-style prefix growth using compact projection
     arrays (position + prefix utility).
  5) Global candidate deduplication.
  6) Exact distributed verification with prefix-sharing candidate tries.

The implementation accepts the same two-file positive-utility setting used
by pypatternminer/ahus.py:
  - sequence file: item[value] ... -1 ... -2 SUtility:...
  - external utility file: item:utility
When --value-mode quantity is used, value is interpreted as quantity and
multiplied by the external utility.  With --value-mode utility, item[value]
is interpreted as an already-computed occurrence utility and no external
utility file is required.

This is an exact algorithm: local mining only generates candidates; final
global utilities are recomputed exactly across all database partitions.
"""

